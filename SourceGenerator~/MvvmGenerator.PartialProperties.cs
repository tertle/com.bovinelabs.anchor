namespace BovineLabs.SystemPropertyGenerator
{
    using System.Collections.Generic;
    using System.Linq;
    using System.Text;
    using CodeGenHelpers;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp;
    using Microsoft.CodeAnalysis.CSharp.Syntax;
    using Microsoft.CodeAnalysis.Text;

    public sealed partial class MvvmGenerator
    {
        private static readonly SymbolDisplayFormat PartialTypeFormat = new(
            genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters | SymbolDisplayGenericsOptions.IncludeVariance,
            kindOptions: SymbolDisplayKindOptions.IncludeTypeKeyword,
            miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

        private static void EmitPartialProperty(SourceProductionContext context, IPropertySymbol property, SyntaxNode node, bool nullableAnnotations)
        {
            if (node is not PropertyDeclarationSyntax declaration || !property.IsPartialDefinition || property.PartialImplementationPart != null ||
                property.IsStatic || property.IsAbstract || property.IsExtern || property.GetMethod == null || property.SetMethod == null ||
                node.Ancestors().OfType<TypeDeclarationSyntax>().Any(type => !IsPartial(type) || type.Modifiers.Any(SyntaxKind.FileKeyword)))
            {
                context.ReportDiagnostic(Diagnostic.Create(MvvmDiagnostics.InvalidObservablePropertyDescriptor, property.Locations[0], property.Name));
                return;
            }

            var diagnostics = new List<Diagnostic>();
            var methods = GetAlsoExecuteMethods(property, diagnostics);
            foreach (var diagnostic in diagnostics)
            {
                context.ReportDiagnostic(diagnostic);
            }

            var notifications = GetStringAttributeArguments(property, AlsoNotifyChangeForAttributeMetadataName);
            var writer = new CodeWriter(IndentStyle.Spaces);
            writer.AppendLine("// <auto-generated/>");
            writer.AppendLine(nullableAnnotations ? "#nullable enable annotations" : "#nullable disable");
            if (!property.ContainingNamespace.IsGlobalNamespace)
            {
                writer.AppendLine($"namespace {property.ContainingNamespace.ToDisplayString()};");
            }

            var types = GetTypeChain(property.ContainingType);
            foreach (var type in types)
            {
                writer.Block($"partial {type.ToDisplayString(PartialTypeFormat)}");
            }

            if (!HasAttribute(property, "System.Runtime.CompilerServices.CompilerGeneratedAttribute"))
            {
                writer.AppendLine("[global::System.Runtime.CompilerServices.CompilerGenerated]");
            }

            if (!HasAttribute(property, "Unity.Properties.CreatePropertyAttribute"))
            {
                writer.AppendLine("[global::Unity.Properties.CreateProperty]");
            }

            var modifiers = string.Join(" ", declaration.Modifiers.Select(static token => token.Text));
            var typeFormat = QualifiedTypeFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
            var typeName = property.Type.ToDisplayString(typeFormat);
            using (writer.Block($"{modifiers} {typeName} {declaration.Identifier.Text}"))
            {
                foreach (var accessor in declaration.AccessorList.Accessors)
                {
                    var accessorName = string.Join(" ", accessor.Modifiers.Append(accessor.Keyword).Select(static token => token.Text));
                    if (accessor.IsKind(SyntaxKind.GetAccessorDeclaration))
                    {
                        writer.AppendLine($"{accessorName};");
                    }
                    else
                    {
                        using (writer.Block(accessorName))
                        {
                            WriteObservableSetter(writer, "field", methods, notifications);
                        }
                    }
                }
            }

            foreach (var type in types)
            {
                writer.Dispose();
            }

            var typePath = string.Join("+", types.Select(static type => type.MetadataName));
            var namespacePrefix = property.ContainingNamespace.IsGlobalNamespace ? string.Empty : property.ContainingNamespace.ToDisplayString() + ".";
            context.AddSource($"{namespacePrefix}{typePath}.{property.MetadataName}.ObservableProperty.g.cs", SourceText.From(writer.Render(), Encoding.UTF8));
        }
    }
}
